import Foundation
import CryptoKit

// MARK: - 1. Checksum Engine (SFV/CRC32, MD5, SHA1, SHA256, SHA512)

public enum ChecksumKind: String, CaseIterable, Codable, Sendable {
    case crc32 = "sfv"
    case md5 = "md5"
    case sha1 = "sha1"
    case sha256 = "sha256"
    case sha512 = "sha512"

    public var displayName: String {
        switch self {
        case .crc32: return "CRC32 (.sfv)"
        case .md5: return "MD5 (.md5)"
        case .sha1: return "SHA-1 (.sha1)"
        case .sha256: return "SHA-256 (.sha256)"
        case .sha512: return "SHA-512 (.sha512)"
        }
    }

    public var fileExtension: String { rawValue }
}

public enum ChecksumStatus: String, Codable, Sendable {
    case ok = "OK"
    case mismatch = "MISMATCH"
    case missingFile = "MISSING"
    case error = "ERROR"
}

public struct ChecksumVerificationRow: Identifiable, Hashable, Sendable {
    public let id: String
    public let fileName: String
    public let expectedHash: String
    public let actualHash: String
    public let status: ChecksumStatus
}

public enum ChecksumEngine {
    private static let crc32Table: [UInt32] = {
        (0..<256).map { i -> UInt32 in
            var c = UInt32(i)
            for _ in 0..<8 {
                c = (c & 1) != 0 ? (0xEDB88320 ^ (c >> 1)) : (c >> 1)
            }
            return c
        }
    }()

    public static func crc32(ofData data: Data) -> UInt32 {
        var crc: UInt32 = 0xFFFFFFFF
        for byte in data {
            let idx = Int((crc ^ UInt32(byte)) & 0xFF)
            crc = (crc >> 8) ^ crc32Table[idx]
        }
        return crc ^ 0xFFFFFFFF
    }

    public static func crc32(ofFileAt path: String) throws -> String {
        let data = try Data(contentsOf: URL(fileURLWithPath: path), options: [.mappedIfSafe])
        return String(format: "%08X", crc32(ofData: data))
    }

    public static func computeChecksum(ofFileAt path: String, kind: ChecksumKind) throws -> String {
        let data = try Data(contentsOf: URL(fileURLWithPath: path), options: [.mappedIfSafe])
        switch kind {
        case .crc32:
            return String(format: "%08x", crc32(ofData: data))
        case .md5:
            let digest = Insecure.MD5.hash(data: data)
            return digest.map { String(format: "%02x", $0) }.joined()
        case .sha1:
            let digest = Insecure.SHA1.hash(data: data)
            return digest.map { String(format: "%02x", $0) }.joined()
        case .sha256:
            let digest = SHA256.hash(data: data)
            return digest.map { String(format: "%02x", $0) }.joined()
        case .sha512:
            let digest = SHA512.hash(data: data)
            return digest.map { String(format: "%02x", $0) }.joined()
        }
    }

    @discardableResult
    public static func createChecksumManifest(
        forFiles filePaths: [String],
        kind: ChecksumKind,
        outputPath: String? = nil,
        separateFilePerItem: Bool = false
    ) throws -> [String] {
        guard !filePaths.isEmpty else { return [] }

        if separateFilePerItem {
            var created: [String] = []
            for file in filePaths {
                let singleOut = "\(file).\(kind.fileExtension)"
                let res = try createChecksumManifest(
                    forFiles: [file],
                    kind: kind,
                    outputPath: singleOut,
                    separateFilePerItem: false
                )
                created.append(contentsOf: res)
            }
            return created
        }

        let targetManifestPath: String
        if let explicit = outputPath {
            targetManifestPath = explicit
        } else if filePaths.count == 1 {
            targetManifestPath = "\(filePaths[0]).\(kind.fileExtension)"
        } else {
            let dir = (filePaths[0] as NSString).deletingLastPathComponent
            let folderName = (dir as NSString).lastPathComponent
            targetManifestPath = (dir as NSString).appendingPathComponent("\(folderName).\(kind.fileExtension)")
        }

        let baseDir = (targetManifestPath as NSString).deletingLastPathComponent
        var lines: [String] = ["; Generated by CZ.commander for macOS (Apple Silicon)"]

        for filePath in filePaths {
            let relName: String
            if filePath.hasPrefix(baseDir + "/") {
                relName = String(filePath.dropFirst(baseDir.count + 1))
            } else {
                relName = (filePath as NSString).lastPathComponent
            }
            let hash = try computeChecksum(ofFileAt: filePath, kind: kind)
            if kind == .crc32 {
                lines.append("\(relName) \(hash)")
            } else {
                lines.append("\(hash) *\(relName)")
            }
        }

        let text = lines.joined(separator: "\n") + "\n"
        try text.write(toFile: targetManifestPath, atomically: true, encoding: .utf8)
        return [targetManifestPath]
    }

    public static func verifyChecksumManifest(atPath manifestPath: String) throws -> [ChecksumVerificationRow] {
        let content = try String(contentsOfFile: manifestPath, encoding: .utf8)
        let baseDir = (manifestPath as NSString).deletingLastPathComponent
        let ext = (manifestPath as NSString).pathExtension.lowercased()
        let defaultKind = ChecksumKind(rawValue: ext) ?? .sha256

        var results: [ChecksumVerificationRow] = []

        for (lineIdx, rawLine) in content.components(separatedBy: .newlines).enumerated() {
            let line = rawLine.trimmingCharacters(in: .whitespacesAndNewlines)
            if line.isEmpty || line.hasPrefix(";") || line.hasPrefix("#") { continue }

            var fileName = ""
            var expectedHash = ""
            var detectedKind = defaultKind

            if defaultKind == .crc32 || ext == "sfv" {
                // Format: filename.ext 1234abcd
                if let lastSpace = line.lastIndex(of: " ") {
                    fileName = String(line[..<lastSpace]).trimmingCharacters(in: .whitespaces)
                    expectedHash = String(line[line.index(after: lastSpace)...]).trimmingCharacters(in: .whitespaces)
                    detectedKind = .crc32
                }
            } else if let starRange = line.range(of: " *") ?? line.range(of: "  ") {
                expectedHash = String(line[..<starRange.lowerBound]).trimmingCharacters(in: .whitespaces)
                fileName = String(line[starRange.upperBound...]).trimmingCharacters(in: .whitespaces)
                detectedKind = inferKind(fromHashLength: expectedHash.count, fallback: defaultKind)
            } else if let firstSpace = line.firstIndex(of: " ") {
                expectedHash = String(line[..<firstSpace]).trimmingCharacters(in: .whitespaces)
                fileName = String(line[line.index(after: firstSpace)...]).trimmingCharacters(in: CharacterSet(charactersIn: " *"))
                detectedKind = inferKind(fromHashLength: expectedHash.count, fallback: defaultKind)
            }

            guard !fileName.isEmpty && !expectedHash.isEmpty else { continue }
            let fullFilePath = (baseDir as NSString).appendingPathComponent(fileName)

            if !FileManager.default.fileExists(atPath: fullFilePath) {
                results.append(
                    ChecksumVerificationRow(
                        id: "\(lineIdx):\(fileName)",
                        fileName: fileName,
                        expectedHash: expectedHash.lowercased(),
                        actualHash: "—",
                        status: .missingFile
                    )
                )
                continue
            }

            do {
                let actual = try computeChecksum(ofFileAt: fullFilePath, kind: detectedKind)
                let isMatch = actual.lowercased() == expectedHash.lowercased()
                results.append(
                    ChecksumVerificationRow(
                        id: "\(lineIdx):\(fileName)",
                        fileName: fileName,
                        expectedHash: expectedHash.lowercased(),
                        actualHash: actual.lowercased(),
                        status: isMatch ? .ok : .mismatch
                    )
                )
            } catch {
                results.append(
                    ChecksumVerificationRow(
                        id: "\(lineIdx):\(fileName)",
                        fileName: fileName,
                        expectedHash: expectedHash.lowercased(),
                        actualHash: error.localizedDescription,
                        status: .error
                    )
                )
            }
        }

        return results
    }

    private static func inferKind(fromHashLength length: Int, fallback: ChecksumKind) -> ChecksumKind {
        switch length {
        case 8: return .crc32
        case 32: return .md5
        case 40: return .sha1
        case 64: return .sha256
        case 128: return .sha512
        default: return fallback
        }
    }
}

// MARK: - 2. Split & Combine File Engine (.001, .002 + .crc)

public struct CombineResult: Sendable {
    public let outputFilePath: String
    public let totalBytes: Int64
    public let partsCombined: Int
    public let crcVerified: Bool
    public let expectedCRC: String?
    public let actualCRC: String
}

public enum SplitCombineEngine {
    /// Splits `sourceFilePath` into `.001`, `.002`, ... in `destinationDirectory` plus a Total Commander `.crc` manifest
    @discardableResult
    public static func splitFile(
        atPath sourceFilePath: String,
        toDirectory destinationDirectory: String,
        bytesPerPart: Int,
        createCRCFile: Bool = true
    ) throws -> [String] {
        guard bytesPerPart > 0 else {
            throw NSError(domain: "CZCommander.Split", code: 400, userInfo: [NSLocalizedDescriptionKey: "Invalid part size"])
        }
        let fm = FileManager.default
        if !fm.fileExists(atPath: destinationDirectory) {
            try fm.createDirectory(atPath: destinationDirectory, withIntermediateDirectories: true)
        }

        let data = try Data(contentsOf: URL(fileURLWithPath: sourceFilePath))
        let baseName = (sourceFilePath as NSString).lastPathComponent
        let fullCRC = String(format: "%08X", ChecksumEngine.crc32(ofData: data))

        var createdPaths: [String] = []
        var offset = 0
        var partNumber = 1

        if data.isEmpty {
            let partPath = (destinationDirectory as NSString).appendingPathComponent(String(format: "%@.001", baseName))
            try Data().write(to: URL(fileURLWithPath: partPath))
            createdPaths.append(partPath)
        } else {
            while offset < data.count {
                let end = min(data.count, offset + bytesPerPart)
                let slice = data.subdata(in: offset..<end)
                let extStr = String(format: "%03d", partNumber)
                let partPath = (destinationDirectory as NSString).appendingPathComponent("\(baseName).\(extStr)")
                try slice.write(to: URL(fileURLWithPath: partPath), options: .atomic)
                createdPaths.append(partPath)
                offset = end
                partNumber += 1
            }
        }

        if createCRCFile {
            let crcPath = (destinationDirectory as NSString).appendingPathComponent("\(baseName).crc")
            let crcContent = [
                "filename=\(baseName)",
                "size=\(data.count)",
                "crc32=\(fullCRC)"
            ].joined(separator: "\n") + "\n"
            try crcContent.write(toFile: crcPath, atomically: true, encoding: .utf8)
            createdPaths.append(crcPath)
        }

        return createdPaths
    }

    /// Combines `.001`, `.002`... (or starting from `.crc`) into `destinationDirectory` and verifies CRC32
    public static func combineFiles(
        startingFromPath partOrCRCPath: String,
        toDirectory destinationDirectory: String
    ) throws -> CombineResult {
        let fm = FileManager.default
        if !fm.fileExists(atPath: destinationDirectory) {
            try fm.createDirectory(atPath: destinationDirectory, withIntermediateDirectories: true)
        }

        let sourceDir = (partOrCRCPath as NSString).deletingLastPathComponent
        let fileName = (partOrCRCPath as NSString).lastPathComponent
        let basePrefix: String
        if fileName.lowercased().hasSuffix(".crc") {
            basePrefix = String(fileName.dropLast(4))
        } else if let dotIdx = fileName.lastIndex(of: ".") {
            basePrefix = String(fileName[..<dotIdx])
        } else {
            basePrefix = fileName
        }

        let crcFilePath = (sourceDir as NSString).appendingPathComponent("\(basePrefix).crc")
        var targetFileName = basePrefix
        var expectedCRC: String? = nil

        if let crcText = try? String(contentsOfFile: crcFilePath, encoding: .utf8) {
            for line in crcText.components(separatedBy: .newlines) {
                let trimmed = line.trimmingCharacters(in: .whitespacesAndNewlines)
                if trimmed.lowercased().hasPrefix("filename=") {
                    targetFileName = String(trimmed.dropFirst("filename=".count))
                } else if trimmed.lowercased().hasPrefix("crc32=") {
                    expectedCRC = String(trimmed.dropFirst("crc32=".count)).uppercased()
                }
            }
        }

        var combinedData = Data()
        var partIndex = 1
        var partsFound = 0

        while true {
            let partName = String(format: "%@.%03d", basePrefix, partIndex)
            let partPath = (sourceDir as NSString).appendingPathComponent(partName)
            guard fm.fileExists(atPath: partPath) else { break }
            let partData = try Data(contentsOf: URL(fileURLWithPath: partPath))
            combinedData.append(partData)
            partsFound += 1
            partIndex += 1
        }

        guard partsFound > 0 else {
            throw NSError(
                domain: "CZCommander.Combine",
                code: 404,
                userInfo: [NSLocalizedDescriptionKey: "No .001 part files found for \(basePrefix)"]
            )
        }

        let outPath = (destinationDirectory as NSString).appendingPathComponent(targetFileName)
        try combinedData.write(to: URL(fileURLWithPath: outPath), options: .atomic)

        let actualCRC = String(format: "%08X", ChecksumEngine.crc32(ofData: combinedData))
        let crcOK = expectedCRC == nil || expectedCRC?.uppercased() == actualCRC.uppercased()

        return CombineResult(
            outputFilePath: outPath,
            totalBytes: Int64(combinedData.count),
            partsCombined: partsFound,
            crcVerified: crcOK,
            expectedCRC: expectedCRC,
            actualCRC: actualCRC
        )
    }
}

// MARK: - 3. Encode / Decode Engine (MIME Base64 .b64, UUEncode .uue, XXEncode .xxe)

public enum EncodingFormat: String, CaseIterable, Codable, Sendable {
    case mimeBase64 = "b64"
    case uuencode = "uue"
    case xxencode = "xxe"

    public var displayName: String {
        switch self {
        case .mimeBase64: return "MIME Base64 (.b64)"
        case .uuencode: return "UUEncode (.uue)"
        case .xxencode: return "XXEncode (.xxe)"
        }
    }

    public var fileExtension: String { rawValue }
}

public enum EncodeDecodeEngine {
    private static let xxTable = Array("+-0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz".utf8)
    private static let xxReverseTable: [UInt8: UInt8] = {
        var map: [UInt8: UInt8] = [:]
        for (idx, b) in xxTable.enumerated() {
            map[b] = UInt8(idx)
        }
        return map
    }()

    @discardableResult
    public static func encodeFile(
        atPath sourcePath: String,
        toDirectory destinationDirectory: String,
        format: EncodingFormat
    ) throws -> String {
        let fm = FileManager.default
        if !fm.fileExists(atPath: destinationDirectory) {
            try fm.createDirectory(atPath: destinationDirectory, withIntermediateDirectories: true)
        }

        let data = try Data(contentsOf: URL(fileURLWithPath: sourcePath))
        let fileName = (sourcePath as NSString).lastPathComponent
        let outPath = (destinationDirectory as NSString).appendingPathComponent("\(fileName).\(format.fileExtension)")

        switch format {
        case .mimeBase64:
            let b64 = data.base64EncodedString(options: [.lineLength64Characters, .endLineWithLineFeed])
            let header = [
                "MIME-Version: 1.0",
                "Content-Type: application/octet-stream; name=\"\(fileName)\"",
                "Content-Transfer-Encoding: base64",
                "Content-Disposition: attachment; filename=\"\(fileName)\"",
                "",
                b64,
                ""
            ].joined(separator: "\n")
            try header.write(toFile: outPath, atomically: true, encoding: .utf8)

        case .uuencode:
            let encoded = encodeCustom6Bit(data: data, fileName: fileName, isXX: false)
            try encoded.write(toFile: outPath, atomically: true, encoding: .utf8)

        case .xxencode:
            let encoded = encodeCustom6Bit(data: data, fileName: fileName, isXX: true)
            try encoded.write(toFile: outPath, atomically: true, encoding: .utf8)
        }

        return outPath
    }

    @discardableResult
    public static func decodeFile(
        atPath encodedPath: String,
        toDirectory destinationDirectory: String
    ) throws -> String {
        let fm = FileManager.default
        if !fm.fileExists(atPath: destinationDirectory) {
            try fm.createDirectory(atPath: destinationDirectory, withIntermediateDirectories: true)
        }

        let text = try String(contentsOfFile: encodedPath, encoding: .utf8)
        let ext = (encodedPath as NSString).pathExtension.lowercased()
        let fallbackName = ((encodedPath as NSString).lastPathComponent as NSString).deletingPathExtension

        if ext == "uue" || (text.contains("begin ") && !ext.hasSuffix("xxe") && !text.contains("Content-Transfer-Encoding: base64")) {
            let (name, decoded) = decodeCustom6Bit(text: text, fallbackName: fallbackName, isXX: false)
            let outPath = (destinationDirectory as NSString).appendingPathComponent(name)
            try decoded.write(to: URL(fileURLWithPath: outPath), options: .atomic)
            return outPath
        } else if ext == "xxe" {
            let (name, decoded) = decodeCustom6Bit(text: text, fallbackName: fallbackName, isXX: true)
            let outPath = (destinationDirectory as NSString).appendingPathComponent(name)
            try decoded.write(to: URL(fileURLWithPath: outPath), options: .atomic)
            return outPath
        } else {
            // MIME Base64
            var fileName = fallbackName
            var bodyLines: [String] = []
            var inHeaders = text.hasPrefix("MIME-Version:") || text.contains("Content-Transfer-Encoding:")

            for line in text.components(separatedBy: .newlines) {
                let trimmed = line.trimmingCharacters(in: .whitespacesAndNewlines)
                if inHeaders {
                    if let nameRange = trimmed.range(of: "filename=\"") ?? trimmed.range(of: "name=\"") {
                        let after = trimmed[nameRange.upperBound...]
                        if let endQuote = after.firstIndex(of: "\"") {
                            fileName = String(after[..<endQuote])
                        }
                    }
                    if trimmed.isEmpty {
                        inHeaders = false
                    }
                } else if !trimmed.isEmpty && !trimmed.hasPrefix("--") {
                    bodyLines.append(trimmed)
                }
            }

            let joinedB64 = bodyLines.joined()
            guard let decoded = Data(base64Encoded: joinedB64, options: [.ignoreUnknownCharacters]) else {
                throw NSError(domain: "CZCommander.Decode", code: 422, userInfo: [NSLocalizedDescriptionKey: "Invalid Base64 content"])
            }
            let outPath = (destinationDirectory as NSString).appendingPathComponent(fileName)
            try decoded.write(to: URL(fileURLWithPath: outPath), options: .atomic)
            return outPath
        }
    }

    private static func encodeCustom6Bit(data: Data, fileName: String, isXX: Bool) -> String {
        var lines: [String] = ["begin 644 \(fileName)"]
        let bytes = Array(data)
        var offset = 0

        func encodeChar(_ val6: UInt8) -> Character {
            let v = val6 & 0x3F
            if isXX {
                return Character(UnicodeScalar(xxTable[Int(v)]))
            } else {
                return Character(UnicodeScalar(v == 0 ? 96 : (v + 32)))
            }
        }

        while offset < bytes.count {
            let chunkLen = min(45, bytes.count - offset)
            var line = String(encodeChar(UInt8(chunkLen)))
            var i = 0
            while i < chunkLen {
                let b0 = bytes[offset + i]
                let b1 = (i + 1 < chunkLen) ? bytes[offset + i + 1] : 0
                let b2 = (i + 2 < chunkLen) ? bytes[offset + i + 2] : 0

                let c0 = b0 >> 2
                let c1 = ((b0 & 0x03) << 4) | ((b1 & 0xF0) >> 4)
                let c2 = ((b1 & 0x0F) << 2) | ((b2 & 0xC0) >> 6)
                let c3 = b2 & 0x3F

                line.append(encodeChar(c0))
                line.append(encodeChar(c1))
                line.append(encodeChar(c2))
                line.append(encodeChar(c3))
                i += 3
            }
            lines.append(line)
            offset += chunkLen
        }

        lines.append(String(encodeChar(0)))
        lines.append("end")
        return lines.joined(separator: "\n") + "\n"
    }

    private static func decodeCustom6Bit(text: String, fallbackName: String, isXX: Bool) -> (String, Data) {
        var fileName = fallbackName
        var outBytes: [UInt8] = []
        var started = false

        func decodeByte(_ ch: UInt8) -> UInt8 {
            if isXX {
                return xxReverseTable[ch] ?? 0
            } else {
                if ch == 96 || ch == 32 { return 0 }
                return (ch &- 32) & 0x3F
            }
        }

        for rawLine in text.components(separatedBy: .newlines) {
            let line = rawLine.trimmingCharacters(in: .newlines)
            if !started {
                if line.hasPrefix("begin ") {
                    let parts = line.split(separator: " ", maxSplits: 2)
                    if parts.count == 3 {
                        fileName = String(parts[2])
                    }
                    started = true
                }
                continue
            }
            if line == "end" || line.isEmpty { break }
            let ascii = Array(line.utf8)
            guard let first = ascii.first else { continue }
            let lineByteCount = Int(decodeByte(first))
            if lineByteCount == 0 { break }

            var decodedLine: [UInt8] = []
            var idx = 1
            while idx < ascii.count && decodedLine.count < lineByteCount {
                let c0 = decodeByte(ascii[idx])
                let c1 = (idx + 1 < ascii.count) ? decodeByte(ascii[idx + 1]) : 0
                let c2 = (idx + 2 < ascii.count) ? decodeByte(ascii[idx + 2]) : 0
                let c3 = (idx + 3 < ascii.count) ? decodeByte(ascii[idx + 3]) : 0

                let b0 = (c0 << 2) | (c1 >> 4)
                let b1 = ((c1 & 0x0F) << 4) | (c2 >> 2)
                let b2 = ((c2 & 0x03) << 6) | c3

                decodedLine.append(b0)
                if decodedLine.count < lineByteCount { decodedLine.append(b1) }
                if decodedLine.count < lineByteCount { decodedLine.append(b2) }
                idx += 4
            }
            outBytes.append(contentsOf: decodedLine.prefix(lineByteCount))
        }

        return (fileName, Data(outBytes))
    }
}
